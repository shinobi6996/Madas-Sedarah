-- Jalankan SQL ini di Supabase > SQL Editor.
-- Data anggota bisa dibaca publik, tetapi hanya akun yang tercantum di admin_users
-- yang boleh menambah, mengubah, atau menghapus data.

create table if not exists public.members (
  id bigint generated by default as identity primary key,
  name text not null,
  fleet_number text not null,
  plate_number text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade
);

alter table public.members enable row level security;
alter table public.admin_users enable row level security;

drop policy if exists "Public can view members" on public.members;
create policy "Public can view members"
on public.members for select
to anon, authenticated
using (true);

drop policy if exists "Admins can insert members" on public.members;
create policy "Admins can insert members"
on public.members for insert
to authenticated
with check (exists (select 1 from public.admin_users a where a.user_id = auth.uid()));

drop policy if exists "Admins can update members" on public.members;
create policy "Admins can update members"
on public.members for update
to authenticated
using (exists (select 1 from public.admin_users a where a.user_id = auth.uid()))
with check (exists (select 1 from public.admin_users a where a.user_id = auth.uid()));

drop policy if exists "Admins can delete members" on public.members;
create policy "Admins can delete members"
on public.members for delete
to authenticated
using (exists (select 1 from public.admin_users a where a.user_id = auth.uid()));

-- Setiap pengguna hanya boleh melihat baris admin_users miliknya sendiri.
drop policy if exists "Admins can view own admin status" on public.admin_users;
create policy "Admins can view own admin status"
on public.admin_users for select
to authenticated
using (user_id = auth.uid());

grant select on public.members to anon, authenticated;
grant insert, update, delete on public.members to authenticated;
grant select on public.admin_users to authenticated;
grant usage, select on sequence public.members_id_seq to authenticated;

